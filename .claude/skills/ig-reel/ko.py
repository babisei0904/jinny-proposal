EOJEOL_RE = re.compile(r"[가-힣A-Za-z0-9$%]+")


def eojeols(text):
    return EOJEOL_RE.findall(re.sub(r"(?<=\d),(?=\d)", "", text))


def stem(eojeol):
    for j in JOSA:
        if eojeol.endswith(j) and len(eojeol) - len(j) >= 2:
            return eojeol[: -len(j)]
    return eojeol


def content_stems(text):
    out = set()
    for e in eojeols(text):
        s = stem(e)
        if s in KO_STOPWORDS or e in KO_STOPWORDS:
            continue
        if len(s) >= 2 or NUM_RE.fullmatch(s):
            out.add(s)
    return out


