#!/usr/bin/env python3
"""
ko.py - 한국어 보정 모듈. hookscore.py 와 beats.py 가 한글 문장을 만나면 이걸 쓴다.

영어판은 "단어 수 / 분당 단어(wpm)" 로 말하는 시간을 잰다. 한국어는 띄어쓰기
단위(어절)가 영어 단어보다 훨씬 길어서 그 방식이 안 맞는다. 그래서 여기서는
**소리 나는 음절 수 / 초당 음절(sps)** 로 잰다.

  - 한글 글자 1개 = 1음절
  - 숫자는 읽는 소리로 바꿔 센다:  420만원 -> 사백이십만원 -> 6음절
                                   3일    -> 삼일         -> 2음절
                                   1.5    -> 일점오       -> 3음절
  - 기호: % -> 퍼센트(3), $ -> 달러(2), ~ -> 부터(0, 읽지 않음으로 처리)
  - 영문 단어는 모음 덩어리 수로 대충 센다 (Airbnb ≈ 3)

기본 속도 6.5음절/초는 릴스 내레이션 속도를 어림잡은 값이다. 정확한 값은
벤치마킹 릴스를 실측해서 --sps 로 맞추는 게 맞다.

판정 기준(구체성/긴장/앞배치/말 걸기)도 영어 대문자·you 대신 한국어 단서로
바꿨다. 목록은 이 파일 맨 위 상수에 있고, 고쳐 쓰라고 만든 것이다.
"""

import re

# ---------------------------------------------------------------- 감지

HANGUL_RE = re.compile(r"[가-힣]")
LATIN_RE = re.compile(r"[A-Za-z]")


def is_korean(text):
    """한글이 영문보다 많으면 한국어로 본다."""
    h = len(HANGUL_RE.findall(text))
    return h > 0 and h >= len(LATIN_RE.findall(text))


# ---------------------------------------------------------------- 음절 세기

DEFAULT_SPS = 6.5          # 초당 음절. 실측 후 --sps 로 덮어쓴다.

NUM_RE = re.compile(r"\d+(?:\.\d+)?")
LATIN_WORD_RE = re.compile(r"[A-Za-z]+")
SYMBOL_SYLLABLES = {"%": 3, "$": 2, "₩": 1, "+": 2, "x": 0}


def _group_syllables(n):
    """0~9999 를 한자어로 읽을 때 음절 수. 십/백/천 앞의 1(일)은 안 읽는다."""
    count = 0
    for unit_pos, d in enumerate(reversed(str(n))):
        d = int(d)
        if d == 0:
            continue
        if unit_pos == 0:
            count += 1                       # 일~구
        else:
            count += 1 if d == 1 else 2      # 십 / 이십
    return count


def number_syllables(token):
    """'420' -> 4 (사백이십),  '42000' -> 4 (사만이천),  '1.5' -> 3 (일점오)."""
    if "." in token:
        whole, frac = token.split(".", 1)
        return number_syllables(whole) + 1 + len(frac)
    n = int(token)
    if n == 0:
        return 1                             # 영 / 공
    total, big = 0, 0
    while n:
        n, group = divmod(n, 10000)
        if group:
            g = _group_syllables(group)
            if big and group == 1:
                g = 0 if big == 1 else 1     # "만" / "일억"
            total += g + (1 if big else 0)   # 만 / 억 / 조
        big += 1
    return total


def latin_syllables(word):
    return max(1, len(re.findall(r"[aeiouy]+", word.lower())))


def syllables(text):
    """말할 때 나는 음절 수."""
    t = re.sub(r"(?<=\d),(?=\d)", "", text)
    count = len(HANGUL_RE.findall(t))
    for m in NUM_RE.finditer(t):
        count += number_syllables(m.group())
    for m in LATIN_WORD_RE.finditer(t):
        count += latin_syllables(m.group())
    for sym, n in SYMBOL_SYLLABLES.items():
        if sym != "x":
            count += t.count(sym) * n
    return count


