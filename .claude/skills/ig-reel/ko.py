def concrete(text):
    """확인 가능한 것들: 숫자+단위, 말로 한 숫자, 지명/브랜드."""
    nums = [m.group().strip() for m in KO_NUMBER_RE.finditer(text) if m.group().strip()]
    spoken = [m.group() for m in KO_SPOKEN_NUM_RE.finditer(text)]
    propers = [p for p in KO_PROPER if p in text]
    # "도쿄" 안의 "도" 같은 겹침은 없지만, "오사카"와 "사카" 같은 건 목록에 없으니 그대로 둔다.
    return nums, spoken, propers


